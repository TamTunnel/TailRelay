func TestStripForSetconf(t *testing.T) {
	in := `# Generated by Tailrelay (wg0)
[Interface]
PrivateKey = aaaa
Address = 10.7.0.1/24, fd00::1/64
ListenPort = 51820
MTU = 1420
DNS = 1.1.1.1

[Peer]
# phone
PublicKey = bbbb
PresharedKey = cccc
AllowedIPs = 10.7.0.2/32, fd00::2/128
`
	out := StripForSetconf(in)
	for _, want := range []string{"PrivateKey = aaaa", "ListenPort = 51820", "[Peer]", "AllowedIPs = 10.7.0.2/32, fd00::2/128", "# phone"} {
		if !strings.Contains(out, want) {
			t.Errorf("stripped config missing %q:\n%s", want, out)
		}
	}
	for _, banned := range []string{"Address =", "MTU =", "DNS ="} {
		if strings.Contains(out, banned) {
			t.Errorf("stripped config still contains %q:\n%s", banned, out)
		}
	}
}
