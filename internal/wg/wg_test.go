func TestNextClientIPv6(t *testing.T) {
	// Basic: first client gets ::2.
	ip, err := NextClientIPv6("fd12:3456:789a::/64", map[string]bool{})
	if err != nil || ip != "fd12:3456:789a::2" {
		t.Errorf("got %q, %v; want fd12:3456:789a::2", ip, err)
	}
	// Skips taken addresses.
	ip, err = NextClientIPv6("fd12:3456:789a::/64",
		map[string]bool{"fd12:3456:789a::2": true, "fd12:3456:789a::3": true})
	if err != nil || ip != "fd12:3456:789a::4" {
		t.Errorf("got %q, %v; want fd12:3456:789a::4", ip, err)
	}
	// Mask-aware: /120 offers ::2..::ff only.
	ip, err = NextClientIPv6("fd12:3456:789a::/120", map[string]bool{})
	if err != nil || ip != "fd12:3456:789a::2" {
		t.Errorf("got %q, %v; want fd12:3456:789a::2", ip, err)
	}
	taken := map[string]bool{}
	for i := 2; i <= 0xff; i++ {
		taken["fd12:3456:789a::"+strconv.FormatInt(int64(i), 16)] = true
	}
	if _, err := NextClientIPv6("fd12:3456:789a::/120", taken); err == nil {
		t.Error("expected exhaustion for a full /120")
	}
	// Address just past the /120 must never be offered.
	if _, err := NextClientIPv6("fd12:3456:789a::/120",
		map[string]bool{"fd12:3456:789a::1:0": true}); err == nil {
		// ::1:0 is outside the /120; allocator must not hand it out.
		// (This case is covered by exhaustion above; kept as documentation.)
	}
	// /126 is the smallest usable pool (::1 server, ::2 and ::3 clients).
	if ip, err := NextClientIPv6("fd00::/126", map[string]bool{}); err != nil || ip != "fd00::2" {
		t.Errorf("got %q, %v; want fd00::2", ip, err)
	}
	// /127 and /128 can't hold server + client.
	for _, p := range []string{"fd00::/127", "fd00::1/128"} {
		if _, err := NextClientIPv6(p, map[string]bool{}); err == nil {
			t.Errorf("expected error for tiny pool %s", p)
		}
	}
	// IPv4 and garbage rejected.
	if _, err := NextClientIPv6("10.7.0.0/24", map[string]bool{}); err == nil {
		t.Error("expected error for IPv4 pool")
	}
	if _, err := NextClientIPv6("nope", map[string]bool{}); err == nil {
		t.Error("expected error for bad CIDR")
	}
}

